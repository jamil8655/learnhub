class InternationalizationService {
  constructor() {
    this.currentLanguage = this.loadLanguage();
    this.applyLanguage(this.currentLanguage);
  }

  loadLanguage() {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && ['en', 'ur', 'ar'].includes(saved)) {
      return saved;
    }
    return 'en'; // Default to English
  }

  getLanguage() {
    return this.currentLanguage || 'en';
  }

  getCurrentLanguage() {
    return this.currentLanguage || 'en';
  }

  isRTL() {
    return this.currentLanguage === 'ur' || this.currentLanguage === 'ar';
  }

  setLanguage(lang) {
    if (!['en', 'ur', 'ar'].includes(lang)) return;
    this.currentLanguage = lang;
    localStorage.setItem(LANG_STORAGE_KEY, lang);
    this.applyLanguage(lang);

    // Close mobile drawer if open
    const drawer = document.getElementById('mobile-menu-drawer');
    if (drawer) drawer.classList.add('hidden');

    window.dispatchEvent(new CustomEvent('learnhub:language_changed', { detail: { language: lang } }));
  }

  t(key, fallback = '') {
    const dict = TRANSLATIONS[this.currentLanguage] || TRANSLATIONS['en'];
    if (dict && dict[key] !== undefined) {
      return dict[key];
    }
    // Fallback to English dictionary
    if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key] !== undefined) {
      return TRANSLATIONS['en'][key];
    }
    return fallback || key;
  }

  applyLanguage(lang = this.currentLanguage) {
    if (!lang || !['en', 'ur', 'ar'].includes(lang)) {
      lang = this.currentLanguage || 'en';
    }
    this.currentLanguage = lang;
    const isRtl = lang === 'ur' || lang === 'ar';

    // 1. Root HTML tag attributes
    if (document.documentElement) {
      document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
      document.documentElement.lang = lang;
    }

    // 2. Body font switching
    if (document.body) {
      document.body.classList.remove('font-urdu', 'font-arabic', 'font-sans');
      if (lang === 'ur') {
        document.body.classList.add('font-urdu');
      } else if (lang === 'ar') {
        document.body.classList.add('font-arabic');
      } else {
        document.body.classList.add('font-sans');
      }
    }

    // 3. Update active language switcher buttons
    const langLabel = document.getElementById('current-lang-label');
    if (langLabel) {
      if (lang === 'ur') langLabel.textContent = '🇵🇰 اردو';
      else if (lang === 'ar') langLabel.textContent = '🇸🇦 العربية';
      else langLabel.textContent = '🇬🇧 English';
    }

    // Highlight drawer mobile language buttons
    const mobileBtnUr = document.getElementById('mobile-lang-ur');
    const mobileBtnAr = document.getElementById('mobile-lang-ar');
    const mobileBtnEn = document.getElementById('mobile-lang-en');
    const activeClass = 'bg-emerald-600 text-white shadow-sm';
    const inactiveClass = 'bg-slate-200 dark:bg-slate-700 hover:bg-slate-300 dark:hover:bg-slate-600 text-slate-700 dark:text-slate-200';

    if (mobileBtnUr && mobileBtnAr && mobileBtnEn) {
      [mobileBtnUr, mobileBtnAr, mobileBtnEn].forEach(btn => {
        btn.className = 'px-2.5 py-1 rounded-xl text-[11px] font-bold ' + inactiveClass;
      });
      if (lang === 'ur') mobileBtnUr.className = 'px-2.5 py-1 rounded-xl text-[11px] font-bold ' + activeClass;
      else if (lang === 'ar') mobileBtnAr.className = 'px-2.5 py-1 rounded-xl text-[11px] font-bold ' + activeClass;
      else mobileBtnEn.className = 'px-2.5 py-1 rounded-xl text-[11px] font-bold ' + activeClass;
    }

    // 4. Translate all DOM elements with attributes
    this.translateDOM();

    // 5. Re-render UI components and active views
    if (window.App && typeof window.App.updateNavbarUserUI === 'function') {
      window.App.updateNavbarUserUI();
    }
    if (window.Router && typeof window.Router.handleRouting === 'function') {
      window.Router.handleRouting();
    }
  }

  translateDOM(root = document) {
    if (!root) return;

    // Elements with data-i18n
    root.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.textContent = this.t(key, el.textContent);
      }
    });

    // Placeholders with data-i18n-placeholder
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) {
        el.setAttribute('placeholder', this.t(key, el.getAttribute('placeholder')));
      }
    });

    // Titles with data-i18n-title
    root.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (key) {
        el.setAttribute('title', this.t(key, el.getAttribute('title')));
      }
    });

    // Aria-labels with data-i18n-aria-label
    root.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria-label');
      if (key) {
        el.setAttribute('aria-label', this.t(key, el.getAttribute('aria-label')));
      }
    });
  }
}

// Global Singleton Instance
window.I18N = new InternationalizationService();
window.__ = (key, fallback) => window.I18N.t(key, fallback);
